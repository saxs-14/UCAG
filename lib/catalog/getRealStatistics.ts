export async function fetchRealStatistics(): Promise<Statistic[]> {
  try {
    const db = getAdminDb();
    const snap = await db.collection("statistics").get();
    const dbStats = snap.docs.map((doc) => ({ ...(doc.data() as Omit<Statistic, "id">), id: doc.id }));
    
    // Combine Firestore docs with fallback verified stats for any missing datasets
    const dbDatasets = new Set(dbStats.map((s) => s.dataset));
    const missingVerifiedStats = VERIFIED_REAL_STATISTICS.filter(
      (s) => !dbDatasets.has(s.dataset)
    );
    
    return [...dbStats, ...missingVerifiedStats];
  } catch (error) {
    console.error("Failed to fetch statistics from Firestore, returning verified static defaults", error);
    return VERIFIED_REAL_STATISTICS;
  }
}
